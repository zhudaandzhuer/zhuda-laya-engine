/** Every issue in the built-in presets (none expected): for tests and for a preset of one's own. */
export function validateZhudaEffectPreset3D(preset: ZhudaEffectPreset3D): string[] {
  const issues = validateParticleEffect3D(preset?.effect);
  if (!preset || !['loop', 'burst'].includes(preset.kind)) issues.push('kind: loop or burst');
  if (!(Number.isFinite(preset?.seconds) && preset.seconds > 0)) issues.push('seconds: above 0');
  if (
    !Array.isArray(preset?.sizeMeters) ||
    preset.sizeMeters.length !== 3 ||
    !preset.sizeMeters.every((n) => Number.isFinite(n) && n > 0)
  )
    issues.push('sizeMeters: [width, height, depth] above 0');
  return issues;
}
