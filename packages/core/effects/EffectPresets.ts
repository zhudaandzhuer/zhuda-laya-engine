/**
 * Ready effects for a 3D scene, as data: each is a `ParticleEffectSpec3D` in
 * metres and seconds whose emitters name the built-in sprites
 * (`EffectSprites.ts`). Nothing is loaded from a file. `ZhudaEffect3D` plays
 * one; a film scene's `effect` node places one.
 *
 * `kind` says how it runs: `loop` goes on until stopped (a fire, rain);
 * `burst` happens once from its start and ends by itself (an explosion, a
 * hit). `sizeMeters` is roughly how much room it takes at scale 1, to place it
 * and to frame a camera on it.
 */
import type { ParticleEffectSpec3D, ParticleEmitterSpec3D } from '../particles/ParticleTypes3D.ts';
import { validateParticleEffect3D } from '../particles/ParticleTypes3D.ts';
import type { ZhudaEffectSpriteId } from './EffectSprites.ts';

export interface ZhudaEffectPreset3D {
  description: string;
  kind: 'loop' | 'burst';
  /** Width, height and depth it fills at scale 1, in metres. */
  sizeMeters: [number, number, number];
  /** A burst is over after this long; a loop has settled into its look by then. */
  seconds: number;
  effect: ParticleEffectSpec3D;
}

type Emitter = Omit<ParticleEmitterSpec3D, 'texture' | 'seed' | 'space' | 'direction'> & {
  texture: ZhudaEffectSpriteId;
  direction?: ParticleEmitterSpec3D['direction'];
  space?: ParticleEmitterSpec3D['space'];
};
const UP = { x: 0, y: 1, z: 0 },
  DOWN = { x: 0, y: -1, z: 0 };
const preset = (
  description: string,
  kind: 'loop' | 'burst',
  sizeMeters: [number, number, number],
  seconds: number,
  emitters: Emitter[],
): ZhudaEffectPreset3D => ({
  description,
  kind,
  sizeMeters,
  seconds,
  effect: {
    schemaVersion: 1,
    dimension: 3,
    emitters: emitters.map((e, i) => ({
      space: 'world',
      direction: UP,
      seed: 1000 + i * 77,
      ...e,
    })) as ParticleEmitterSpec3D[],
  },
});
const fade = (peak: number, inAt = 0.15) => [
  { time: 0, value: 0 },
  { time: inAt, value: peak },
  { time: 1, value: 0 },
];
const ALL = Math.PI;

