#!/usr/bin/env node
// Writes packages/core/runtime3d/SmaaTables.ts from the two lookup pictures
// that three.js carries in examples/jsm/postprocessing/SMAAPass.js (they are
// the AreaTex and SearchTex of SMAA 2.8). Run it again only to take the
// tables from another three.js release:
//
//   node scripts/build-smaa-tables.mjs <path to three>/examples/jsm/postprocessing/SMAAPass.js
//
// Provenance and licences: vendor/threejs-post/README.md.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { PNG } from 'pngjs';
import * as prettier from 'prettier';

const source = process.argv[2];
if (!source || !fs.existsSync(source)) {
  console.error(
    'usage: node scripts/build-smaa-tables.mjs <three>/examples/jsm/postprocessing/SMAAPass.js',
  );
  process.exit(2);
}
const bytes = fs.readFileSync(source);
const uris = bytes.toString('utf8').match(/data:image\/png;base64,[A-Za-z0-9+/=]*/g) ?? [];
if (uris.length !== 2)
  throw Error('Expected the area and the search picture, found ' + uris.length);
const [area, search] = uris.map((uri) => PNG.sync.read(Buffer.from(uri.split(',')[1], 'base64')));
if (area.width !== 160 || area.height !== 560) throw Error('Unexpected area picture size');
if (search.width !== 66 || search.height !== 33) throw Error('Unexpected search picture size');

// SMAA 1x without diagonal patterns reads the first 80 by 80 texels only: the
// orthogonal patterns (16 texels a pattern, five patterns a side) of the
// first of the seven sub-sample rows. Red and green hold the two areas.
const AREA = 80;
const areaBytes = Buffer.alloc(AREA * AREA * 2);
for (let y = 0; y < AREA; y++)
  for (let x = 0; x < AREA; x++) {
    areaBytes[(y * AREA + x) * 2] = area.data[(y * area.width + x) * 4];
    areaBytes[(y * AREA + x) * 2 + 1] = area.data[(y * area.width + x) * 4 + 1];
  }
const searchBytes = Buffer.alloc(search.width * search.height);
for (let i = 0; i < searchBytes.length; i++) searchBytes[i] = search.data[i * 4];

const sha = (data) => crypto.createHash('sha256').update(data).digest('hex');
const lines = (text) =>
  text
    .match(/.{1,96}/g)
    .map((line) => `  '${line}',`)
    .join('\n');
const out = `// Generated by scripts/build-smaa-tables.mjs; do not edit by hand.
// The lookup tables of SMAA 2.8 (Jimenez, Echevarria, Masia, Navarro,
// Gutierrez; MIT), as three.js carries them (MIT). Provenance and licences:
// vendor/threejs-post/README.md.

/** Edge of the area table in texels: red and green, one byte each, row by row. */
export const ZHUDA_SMAA_AREA_SIZE = ${AREA};
/** Width and height of the search table: one byte a texel, row by row. */
export const ZHUDA_SMAA_SEARCH_SIZE: readonly [number, number] = [${search.width}, ${search.height}];
/** SHA-256 of the decoded bytes, in hex. */
export const ZHUDA_SMAA_AREA_SHA256 = '${sha(areaBytes)}';
export const ZHUDA_SMAA_SEARCH_SHA256 = '${sha(searchBytes)}';

const AREA = [
${lines(areaBytes.toString('base64'))}
].join('');
const SEARCH = [
${lines(searchBytes.toString('base64'))}
].join('');

function decode(text: string): Uint8Array {
  const binary = atob(text);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

/** The area table: \`ZHUDA_SMAA_AREA_SIZE\` squared texels of two bytes. */
export function zhudaSmaaAreaTable(): Uint8Array {
  return decode(AREA);
}
/** The search table: \`ZHUDA_SMAA_SEARCH_SIZE\` texels of one byte. */
export function zhudaSmaaSearchTable(): Uint8Array {
  return decode(SEARCH);
}
`;
const target = path.resolve(import.meta.dirname, '../packages/core/runtime3d/SmaaTables.ts');
// Written as the formatter leaves it, so that writing it again changes nothing.
fs.writeFileSync(
  target,
  await prettier.format(out, { ...(await prettier.resolveConfig(target)), filepath: target }),
);
console.log(
  JSON.stringify(
    {
      source: { bytes: bytes.length, sha256: sha(bytes) },
      area: { texels: [AREA, AREA], bytes: areaBytes.length, sha256: sha(areaBytes) },
      search: {
        texels: [search.width, search.height],
        bytes: searchBytes.length,
        sha256: sha(searchBytes),
      },
      written: path.relative(process.cwd(), target),
    },
    null,
    2,
  ),
);
