#!/usr/bin/env node
// Official browser SDK release: build → ZIP → upload → verify remote bytes →
// record the release → pin templates and docs to it.
//
//   node scripts/release-browser-sdk.mjs --publish     (needs GAME_UPLOAD_TOKEN)
//   node scripts/release-browser-sdk.mjs --pin         (rewrite pins from the record)
//   node scripts/release-browser-sdk.mjs --check       (fail when pins are stale)
//
// docs/browser-sdk-releases.json is the single record of published releases;
// its first entry is the latest. Templates and docs are generated from it, so a
// repository checkout always points at the newest published bundle.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const recordFile = path.join(root, 'docs/browser-sdk-releases.json');
const docFile = path.join(root, 'docs/browser-sdk.md');
const templateDir = path.join(root, 'examples/browser-sdk');
const START = '<!-- browser-sdk-release:start';
const END = '<!-- browser-sdk-release:end -->';
const PROFILE_TEXT = {
  'zhuda-2d.js': 'core、2D WebGL、UI、公開 Zhuda SDK',
  'zhuda-3d.js': '上述內容加上 3D、3D WebGL',
  'zhuda-3d-gltf.js': '3D 加上 glTF、postProcess',
  'zhuda-2d-webgpu.js': '2D WebGPU、UI、內嵌 Shader WASM',
  'zhuda-3d-webgpu.js': '2D/3D WebGPU、UI、內嵌 Shader WASM',
  'zhuda-3d-gltf-webgpu.js': 'WebGPU 加上 glTF、postProcess、Shader WASM',
};
const ZIP_LIMIT = 50_000_000;

export function readRecord(file = recordFile) {
  const record = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (record.schemaVersion !== 1 || !Array.isArray(record.releases) || !record.releases.length)
    throw Error(`${path.relative(root, file)}: invalid browser SDK release record`);
  const latest = record.releases[0];
  if (!/^https:\/\/[^/]+\/apps\/[a-z0-9_-]+\/releases\/[0-9a-f]{32}\/$/.test(latest.contentUrl))
    throw Error('Latest browser SDK release has no immutable content URL');
  for (const [file, entry] of Object.entries(latest.files || {}))
    if (!PROFILE_TEXT[file] || !/^sha384-[A-Za-z0-9+/]+=*$/.test(entry.integrity))
      throw Error(`Latest browser SDK release has an invalid entry for ${file}`);
  if (Object.keys(latest.files || {}).length !== Object.keys(PROFILE_TEXT).length)
    throw Error('Latest browser SDK release must list every bundle profile');
  return record;
}

const fmt = (n) => n.toLocaleString('en-US');
function releaseBlock(record) {
  const [latest, ...older] = record.releases;
  const rows = Object.keys(PROFILE_TEXT).map(
    (file) => `| \`${file}\` | ${PROFILE_TEXT[file]} | ${fmt(latest.files[file].bytes)} |`,
  );
  return [
    `${START} (generated by scripts/release-browser-sdk.mjs from docs/browser-sdk-releases.json) -->`,
    `本次固定發行：**${latest.version}**（${latest.summary}）。`,
    `最新版本永遠記錄在 [browser-sdk-releases.json](browser-sdk-releases.json) 的第一筆，`,
    `[SDK 入口](${record.launchUrl}) 也總是開啟最新版本。`,
    '歷史固定版本仍保留，請依需求固定完整版本網址：',
    older.map((r) => `[${r.version}](${r.contentUrl})`).join('、\n') + '。',
    '',
    `\`${latest.contentUrl}\``,
    '',
    '| 檔案 | 包含內容 | 未壓縮 bytes |',
    '| --- | --- | ---: |',
    ...rows,
    END,
  ].join('\n');
}

// Every hosted bundle URL plus its integrity attribute, in templates and docs.
const PIN =
  /(https:\/\/[^"\s]+\/apps\/[a-z0-9_-]+\/releases\/)[0-9a-f]{32}\/(zhuda-[a-z0-9-]+\.js)("\s+integrity=")(sha384-[A-Za-z0-9+/=]+)(")/g;
const PIN_LINES =
  /(src="https:\/\/[^"]+\/apps\/[a-z0-9_-]+\/releases\/)[0-9a-f]{32}\/(zhuda-[a-z0-9-]+\.js)("\n\s*integrity=")(sha384-[A-Za-z0-9+/=]+)(")/g;

function pinText(text, latest, where) {
  const replace = (all, base, file, mid, _old, tail) => {
    const entry = latest.files[file];
    if (!entry) throw Error(`${where}: ${file} is not part of release ${latest.version}`);
    return latest.contentUrl.replace(/\/$/, '') + '/' + file + mid + entry.integrity + tail;
  };
  return text
    .replace(PIN, replace)
    .replace(
      PIN_LINES,
      (all, base, file, mid, old, tail) => 'src="' + replace(all, base, file, mid, old, tail),
    );
}

export function pinnedFiles(record = readRecord()) {
  const latest = record.releases[0];
  const out = new Map();
  for (const name of fs
    .readdirSync(templateDir)
    .filter((f) => f.endsWith('.html'))
    .sort()) {
    const file = path.join(templateDir, name);
    out.set(file, pinText(fs.readFileSync(file, 'utf8'), latest, name));
  }
  let doc = fs.readFileSync(docFile, 'utf8');
  const a = doc.indexOf(START),
    b = doc.indexOf(END);
  if (a < 0 || b < a) throw Error('docs/browser-sdk.md: missing browser-sdk-release markers');
  doc = doc.slice(0, a) + releaseBlock(record) + doc.slice(b + END.length);
  out.set(docFile, pinText(doc, latest, 'docs/browser-sdk.md'));
  return out;
}

export function staleFiles(record = readRecord()) {
  return [...pinnedFiles(record)]
    .filter(([file, text]) => fs.readFileSync(file, 'utf8') !== text)
    .map(([file]) => path.relative(root, file));
}

function writePins(record) {
  for (const [file, text] of pinnedFiles(record)) fs.writeFileSync(file, text);
}

// Store-only ZIP of a flat directory (no ZIP64, no symlinks, no hidden files).
export function zipDirectory(dir) {
  const locals = [],
    central = [];
  let offset = 0;
  for (const name of fs.readdirSync(dir).sort()) {
    const file = path.join(dir, name);
    const stat = fs.lstatSync(file);
    if (name.startsWith('.') || name === 'deployment.json') continue;
    if (!stat.isFile()) throw Error(`Refusing non-regular release entry: ${name}`);
    const data = fs.readFileSync(file),
      nameBytes = Buffer.from(name, 'utf8'),
      crc = zlib.crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    const head = Buffer.alloc(46);
    head.writeUInt32LE(0x02014b50, 0);
    head.writeUInt16LE(20, 4);
    head.writeUInt16LE(20, 6);
    head.writeUInt16LE(0x0800, 8);
    head.writeUInt32LE(crc, 16);
    head.writeUInt32LE(data.length, 20);
    head.writeUInt32LE(data.length, 24);
    head.writeUInt16LE(nameBytes.length, 28);
    head.writeUInt32LE(offset, 42);
    locals.push(local, nameBytes, data);
    central.push(head, nameBytes);
    offset += 30 + nameBytes.length + data.length;
  }
  const centralBytes = Buffer.concat(central),
    end = Buffer.alloc(22),
    count = central.length / 2;
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(count, 8);
  end.writeUInt16LE(count, 10);
  end.writeUInt32LE(centralBytes.length, 12);
  end.writeUInt32LE(offset, 16);
  const zip = Buffer.concat([...locals, centralBytes, end]);
  if (zip.length > ZIP_LIMIT)
    throw Error(`Release ZIP is ${zip.length} bytes (limit ${ZIP_LIMIT})`);
  return zip;
}

function curl(args, input) {
  return execFileSync(
    'curl',
    ['--fail-with-body', '--silent', '--show-error', '--connect-timeout', '10', ...args],
    { input, maxBuffer: 64e6 },
  );
}

async function publish(outDir, record, summary) {
  const token = process.env.GAME_UPLOAD_TOKEN;
  if (!token) throw Error('Set GAME_UPLOAD_TOKEN to publish (never commit it)');
  const { buildBrowserSdk } = await import('../packages/compiler/browser-sdk.mjs');
  const { manifest } = await buildBrowserSdk({ engineRoot: root, outDir });
  if (record.releases.some((r) => r.version === manifest.version))
    throw Error(`Browser SDK ${manifest.version} is already recorded; bump package.json first`);
  const zip = zipDirectory(outDir);
  const zipSha256 = crypto.createHash('sha256').update(zip).digest('hex');
  const zipFile = path.join(path.dirname(outDir), `zhuda-browser-sdk-${manifest.version}.zip`);
  fs.writeFileSync(zipFile, zip);
  const title = encodeURIComponent(`Zhuda Engine Browser SDK ${manifest.version}`);
  // The token travels only in curl's stdin config, never in argv, files or logs.
  const config = [
    `url = "${record.host}/api/v1/games/${record.gameId}/releases?title=${title}"`,
    'request = "POST"',
    `header = "Authorization: Bearer ${token}"`,
    'header = "Content-Type: application/zip"',
    `data-binary = "@${zipFile}"`,
    '',
  ].join('\n');
  const response = JSON.parse(curl(['--max-time', '300', '--config', '-'], config).toString());
  if (response.sha256 !== zipSha256) throw Error('Upload response SHA-256 differs from the ZIP');
  if (!/^[0-9a-f]{32}$/.test(response.version)) throw Error('Upload response has no version');
  const contentUrl = response.content_url;
  for (const name of fs.readdirSync(outDir).filter((n) => !n.startsWith('.'))) {
    const remote = curl(['--max-time', '120', contentUrl + encodeURIComponent(name)]);
    if (!remote.equals(fs.readFileSync(path.join(outDir, name))))
      throw Error(`Hosted ${name} differs from the built release`);
  }
  const headers = curl([
    '--max-time',
    '60',
    '-I',
    '-H',
    'Origin: https://example.com',
    contentUrl + 'zhuda-3d.js',
  ])
    .toString()
    .toLowerCase();
  if (!headers.includes('access-control-allow-origin: *'))
    throw Error('Hosted bundle is not available to cross-origin pages');
  fs.writeFileSync(path.join(outDir, 'deployment.json'), JSON.stringify(response, null, 2) + '\n');
  const files = {};
  for (const entry of Object.values(manifest.profiles))
    files[entry.file] = { bytes: entry.bytes, integrity: entry.integrity };
  record.releases.unshift({
    version: manifest.version,
    contentUrl,
    summary,
    zipSha256,
    files,
  });
  fs.writeFileSync(recordFile, JSON.stringify(record, null, 2) + '\n');
  writePins(readRecord());
  return { version: manifest.version, contentUrl, zipSha256, reused: response.reused };
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const value = (flag) => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : undefined;
  };
  try {
    if (args.includes('--help') || !args.length) {
      console.log(
        'Usage: release-browser-sdk.mjs --publish --summary TEXT [--out DIR] | --pin | --check',
      );
    } else if (args.includes('--check')) {
      const stale = staleFiles();
      if (stale.length) throw Error('Browser SDK pins are stale; run --pin: ' + stale.join(', '));
      console.log(`Browser SDK pins match ${readRecord().releases[0].version}`);
    } else if (args.includes('--pin')) {
      writePins(readRecord());
      console.log(`Pinned templates and docs to ${readRecord().releases[0].version}`);
    } else if (args.includes('--publish')) {
      const summary = value('--summary');
      if (!summary) throw Error('--publish requires --summary TEXT for the docs');
      const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'))).version;
      const outDir = path.resolve(value('--out') || path.join(root, 'dist/browser', version));
      console.log(JSON.stringify(await publish(outDir, readRecord(), summary), null, 2));
    } else throw Error('Unknown arguments: ' + args.join(' '));
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
