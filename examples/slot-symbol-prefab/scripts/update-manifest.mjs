#!/usr/bin/env node
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
export const projectRoot = path.resolve(scriptDir, '..');

const assetKind = id => {
  const extension = path.extname(id).toLowerCase();
  if (extension === '.lh') return 'text';
  if (extension === '.ls') return 'scene';
  if (['.png', '.jpg', '.jpeg', '.webp', '.gif', '.svg'].includes(extension)) return 'image';
  if (['.mp3', '.wav', '.ogg', '.m4a'].includes(extension)) return 'audio';
  if (['.glb', '.gltf', '.fbx', '.obj'].includes(extension)) return 'model';
  if (['.json', '.txt', '.csv', '.atlas', '.skel', '.css', '.ts', '.js'].includes(extension)) return 'text';
  return 'file';
};

function listAssets(root, directory = path.join(root, 'assets')) {
  if (!fs.existsSync(directory)) throw new Error(`Missing asset directory: ${path.relative(root, directory)}`);
  const result = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name === '.DS_Store' || entry.name.endsWith('.bak') || entry.name.includes('.tmp-')) continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) result.push(...listAssets(root, file));
    else if (entry.isFile()) {
      const id = path.relative(path.join(root, 'assets'), file).split(path.sep).join('/');
      result.push({ id, kind: assetKind(id) });
    }
  }
  return result;
}

export function buildManifest(root = projectRoot) {
  const entries = listAssets(root).map(({ id, kind }) => {
    const file = path.join(root, 'assets', id);
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) throw new Error(`Missing declared asset: assets/${id}`);
    const bytes = fs.readFileSync(file);
    return {
      id,
      kind,
      bytes: bytes.byteLength,
      sha256: crypto.createHash('sha256').update(bytes).digest('hex'),
    };
  });
  return { schemaVersion: 1, entries };
}

export function writeManifest(root = projectRoot) {
  const manifest = buildManifest(root);
  const target = path.join(root, 'src', 'asset-manifest.ts');
  const source = `// Generated by scripts/update-manifest.mjs. Run npm run manifest after replacing a symbol image.\n` +
    `import type { AssetManifest } from 'zhuda-laya-engine';\n\n` +
    `export const manifest = ${JSON.stringify(manifest, null, 2)} satisfies AssetManifest;\n`;
  fs.writeFileSync(target, source, 'utf8');
  return { target, manifest };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = writeManifest();
  console.log(`Updated ${path.relative(projectRoot, result.target)} (${result.manifest.entries.length} assets)`);
  for (const entry of result.manifest.entries) console.log(`  ${entry.id}: ${entry.bytes} bytes sha256=${entry.sha256}`);
}
